import type { StoredRecord } from "./records-schema";

function rec(
  collection: string,
  number: string,
  status: string,
  owner: string,
  data: Record<string, unknown>,
  daysAgo: number,
): StoredRecord {
  const ts = Date.now() - daysAgo * 86400000;
  return {
    id: `seed_${collection}_${number}`,
    number,
    collection,
    status,
    owner,
    ownerId: null,
    branchId: data.branchId ? String(data.branchId) : "br_ho",
    framework: data.framework ? String(data.framework) : null,
    data,
    archived: false,
    demo: true,
    createdBy: "system",
    createdById: "system",
    createdAt: ts,
    updatedBy: "system",
    updatedAt: ts,
    comments: [],
    attachments: [],
    history: [{ id: `h_${number}`, actor: "system", action: "Demo record seeded", ts }],
  };
}

