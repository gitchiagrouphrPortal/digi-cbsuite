export function permsForRole(role: string): string[] {
  return ROLE_PERMS[role] ?? EVERYONE;
}

export function roleHas(perm: string, permissions: string[]): boolean {
  return permissions.includes("*") || permissions.includes(perm);
}

export function getRolesList(): string[] {
  return Object.keys(ROLE_PERMS);
}
