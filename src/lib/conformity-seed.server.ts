// Link evidence to clauses by matching evidence title to requiredEvidenceTypes
export function linkEvidenceToClauses(
  clauses: ClauseDTO[],
  evidence: EvidenceDTO[],
): EvidenceDTO[] {
  return evidence.map((ev) => {
    const clauseIds: string[] = [];
    for (const c of clauses) {
      // Match by evidence type/title appearing in requiredEvidenceTypes
      const matches = c.requiredEvidenceTypes.some((req) => {
        const reqLower = req.toLowerCase();
        return (
          ev.title.toLowerCase().includes(reqLower) ||
          ev.evidenceType.toLowerCase().includes(reqLower) ||
          (reqLower.includes("policy") && ev.evidenceType === "Policy") ||
          (reqLower.includes("matrix") && ev.title.toLowerCase().includes("matrix")) ||
          (reqLower.includes("manual") && ev.evidenceType === "Manual") ||
          (reqLower.includes("procedure") && ev.evidenceType === "Procedure") ||
          (reqLower.includes("agreement") && ev.evidenceType === "Contract") ||
          (reqLower.includes("audit report") && ev.evidenceType === "Audit Report") ||
          (reqLower.includes("review") && ev.title.toLowerCase().includes("review")) ||
          (reqLower.includes("duration") && ev.title.toLowerCase().includes("duration")) ||
          (reqLower.includes("authorization") && ev.evidenceType === "Authorization") ||
          (reqLower.includes("register") && ev.evidenceType === "Register") ||
          (reqLower.includes("minutes") && ev.evidenceType === "Minutes") ||
          (reqLower.includes("examination") && ev.evidenceType === "Examination Results") ||
          (reqLower.includes("inspection") && ev.evidenceType === "Inspection Report") ||
          (reqLower.includes("scheme") && ev.evidenceType === "Scheme Document")
        );
      });
      if (matches && (c.frameworkId === ev.frameworkId || ev.frameworkId === "fw_17021")) {
        clauseIds.push(c.id);
      }
    }
    return { ...ev, clauseIds };
  });
}

