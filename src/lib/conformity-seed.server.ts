function buildClauses(seeds: ClauseSeed[], standardId: string, frameworkId: string): ClauseDTO[] {
  return seeds.map((s) => {
    const id = cid(standardId, s.num);
    const parentId = s.parent ? cid(standardId, s.parent) : null;
    return {
      id,
      standardId,
      frameworkId,
      number: s.num,
      parentId,
      title: s.title,
      requirementSummary: s.summary,
      requirementType: s.mandatory === false ? "guidance" : "requirement",
      mandatory: s.mandatory !== false,
      applicability: "Applicable to all certification activities under this framework",
      responsibleProcess: s.modules?.[0] ?? "Quality Management",
      responsibleOwner: "Quality Manager",
      applicableModules: s.modules ?? [],
      requiredEvidenceTypes: s.evidence ?? [],
      assessmentFrequency: "Annual",
      weight: 1,
      assessmentStatus: "not_assessed",
      complianceScore: 0,
      lastAssessed: null,
      nextAssessment: null,
      assessor: null,
    };
  });
}

